#!/usr/bin/env node
// Generates the Effect diagnostic message catalog from the vendored
// effectDiagnosticMessages.json (crates/ts_goport/data/effect/README.md).
// usage: node scripts/effect/gen-effect-messages.mjs [--check]
// Names and keys follow Go's internal/diagnostics/generate.go convertPropertyName.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const input = path.join(root, "crates/ts_goport/data/effect/effectDiagnosticMessages.json");
const catalogOut = path.join(root, "crates/ts_goport/src/diagnostics/effect_catalog.rs");
const namesOut = path.join(root, "crates/ts_goport/src/effect/diag.rs");

function convertPropertyName(text, code) {
  let name = "";
  for (const c of text) {
    if (c === "*") name += "_Asterisk";
    else if (c === "/") name += "_Slash";
    else if (c === ":") name += "_Colon";
    else if (/[\p{L}\p{N}]/u.test(c)) name += c;
    else name += "_";
  }
  name = name.replace(/_+/g, "_").replace(/^_+(\D)/, "$1").replace(/_$/, "");
  const key = `${name.slice(0, 100)}_${code}`;
  if (!/^[A-Z]/.test(name)) name = (name.startsWith("_") ? "X" : "X_") + name;
  return { name, key };
}

const rust = (s) => JSON.stringify(s);
const raw = JSON.parse(fs.readFileSync(input, "utf8"));
const entries = Object.entries(raw)
  .map(([text, { category, code }]) => ({ text, category, code, ...convertPropertyName(text, code) }))
  .sort((a, b) => a.code - b.code);
for (let i = 1; i < entries.length; i++) {
  if (entries[i].code === entries[i - 1].code) throw new Error(`duplicate code ${entries[i].code}`);
}

const header = "// @generated by scripts/effect/gen-effect-messages.mjs; DO NOT EDIT.\n// Source: Effect-TS/tsgo@47cb1ed7704aff44cacaa0f4d2ef24de990cba0e internal/diagnostics/effectDiagnosticMessages.json\n";
let catalog = header + "\n//! The Effect diagnostic messages (codes 377000 to 377999), sorted by code.\n//! Go merges them into its generated catalog; here they are a second table\n//! that `message_by_code` and `message_by_key` also search.\n\nuse super::{Category, Message};\n\npub static EFFECT_CATALOG: &[Message] = &[\n";
for (const e of entries) {
  catalog += `    Message::new(\n        ${e.code},\n        Category::${e.category},\n        ${rust(e.key)},\n        ${rust(e.text)},\n        false,\n        false,\n        false,\n    ),\n`;
}
catalog += "];\n";

let names = header + "\n//! Go `diagnostics.Name` for the Effect messages. Use them as `effect::diag::Name`.\n#![allow(non_upper_case_globals)]\n\nuse crate::diagnostics::{EFFECT_CATALOG, Message};\n\n";
entries.forEach((e, i) => {
  names += `pub static ${e.name}: &Message = &EFFECT_CATALOG[${i}];\n`;
});

// rustfmt the output, so `cargo fmt --check` and --check agree.
const fmt = (text) => execFileSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], { input: text, encoding: "utf8" });
const check = process.argv.includes("--check");
for (const [file, raw] of [[catalogOut, catalog], [namesOut, names]]) {
  const text = fmt(raw);
  if (check) {
    if (fs.readFileSync(file, "utf8") !== text) { console.error(`${file} is stale`); process.exit(1); }
  } else fs.writeFileSync(file, text);
}
console.log(`${entries.length} messages`);
